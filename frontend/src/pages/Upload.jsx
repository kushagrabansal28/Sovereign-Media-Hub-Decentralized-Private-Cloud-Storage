import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { useNostr } from '../hooks/useNostr';
import { useRelays } from '../hooks/useRelays';
import UploadModal from '../components/UploadModal';
import LoginPrompt from '../components/LoginPrompt';

export default function Upload() {
  const { pubkey, signEvent } = useNostr();
  const { publishEvent } = useRelays();
  const navigate = useNavigate();
  
  const [showModal, setShowModal] = useState(false);
  const [publishing, setPublishing] = useState(false);
  const [errorMsg, setErrorMsg] = useState('');

  const handleUploadSuccess = async (nip94EventTemplate) => {
    setShowModal(false);
    setPublishing(true);
    try {
      // 1. Sign the event generated by the UploadModal
      const signedEvent = await signEvent(nip94EventTemplate);
      
      // 2. Publish to strictly configured relays
      await publishEvent(signedEvent);
      
      // 3. Redirect back to gallery
      navigate('/');
    } catch (err) {
      console.error(err);
      setErrorMsg("Failed to publish metadata to relays: " + err.message);
      setPublishing(false);
    }
  };

  if (!pubkey) {
    return (
      <div className="page-container" style={{ display: 'flex', alignItems: 'center', justifyContent: 'center' }}>
        <LoginPrompt />
      </div>
    );
  }

  return (
    <div className="page-container animate-fade-in" style={{ maxWidth: '800px' }}>
      <div className="page-header">
        <h2 className="page-title">Upload Media</h2>
        <p className="page-subtitle">Upload files to your Blossom server and publish metadata to Nostr</p>
      </div>

      {errorMsg && (
        <div className="toast toast-error" style={{ position: 'relative', marginBottom: 'var(--space-lg)' }}>
          {errorMsg}
        </div>
      )}

      {publishing ? (
        <div className="glass-card" style={{ padding: 'var(--space-3xl)', textAlign: 'center' }}>
           <div className="spinner" style={{ margin: '0 auto var(--space-md)' }}></div>
           <h3>Publishing to Relays...</h3>
           <p className="text-secondary">Securing your media metadata on the decentralized network.</p>
        </div>
      ) : (
        <div className="glass-card" style={{ padding: 'var(--space-2xl)', textAlign: 'center' }}>
          <div style={{ fontSize: '4rem', marginBottom: 'var(--space-lg)' }}>📤</div>
          <h3 style={{ fontSize: '1.25rem', marginBottom: 'var(--space-md)' }}>Ready to upload</h3>
          <p style={{ color: 'var(--text-secondary)', marginBottom: 'var(--space-xl)', maxWidth: '400px', margin: '0 auto var(--space-xl)' }}>
            Files are automatically compressed, hashed, and stored securely on your home server.
          </p>
          <button className="btn btn-primary" onClick={() => setShowModal(true)}>
            Start Upload Flow
          </button>
        </div>
      )}

      {showModal && (
        <UploadModal 
          onCancel={() => setShowModal(false)}
          onUploadSuccess={handleUploadSuccess}
        />
      )}
    </div>
  );
}
